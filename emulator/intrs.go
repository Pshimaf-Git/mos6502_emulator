package emulator

type (
	modeFunc = func() Word
	execFunc = func(modeFunc)
)

type instruction struct {
	name string
	mode modeFunc
	exec execFunc
}

func newIntr(name string, mode modeFunc, exec execFunc) instruction {
	return instruction{
		name: name,
		mode: mode,
		exec: exec,
	}
}

